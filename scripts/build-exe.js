#!/usr/bin/env node
"use strict";

/**
 * Builds dist/navy-sync-exporter.exe: one file, no Node install needed on the payroll machine.
 * Run on Windows with Node 20.12+ (the .exe is made from the Node that runs this script).
 *
 *   npm install
 *   npm run keygen            (once, if keys/website-public.pem does not exist yet)
 *   npm run build:exe         or: node scripts/build-exe.js --website-key <path to website-public.pem>
 *
 * Steps: compile the website public key in -> bundle with esbuild -> Node single executable
 * application (SEA) blob -> inject into a copy of node.exe -> write SHA256SUMS.txt for the
 * security review record.
 *
 * If the .exe build fails, the fallback for the test day is dist/exporter.cjs + a portable node.exe:
 *   node.exe exporter.cjs
 */

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { execFileSync } = require("child_process");

const root = path.join(__dirname, "..");
const dist = path.join(root, "dist");
const argv = process.argv.slice(2);
const keyIdx = argv.indexOf("--website-key");
const websiteKeyPath = path.resolve(keyIdx >= 0 ? argv[keyIdx + 1] : path.join(root, "keys", "website-public.pem"));
const isWin = process.platform === "win32";
const exeName = isWin ? "navy-sync-exporter.exe" : "navy-sync-exporter";
const SENTINEL_FUSE = "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2";

// Optional native/cloud modules that tedious may reference but the exporter never loads.
const EXTERNALS = ["keytar", "bufferutil", "utf-8-validate", "dtrace-provider", "@azure/msal-node-extensions"];

function step(msg) {
  console.log(`\n> ${msg}`);
}

async function main() {
  const [major, minor] = process.versions.node.split(".").map(Number);
  if (major < 20 || (major === 20 && minor < 12)) throw new Error(`Node 20.12+ required, this is ${process.version}`);

  step("Compiling the website public key into the exporter");
  if (!fs.existsSync(websiteKeyPath)) throw new Error(`Website public key not found: ${websiteKeyPath}`);
  const pem = fs.readFileSync(websiteKeyPath, "utf8");
  const keyObj = crypto.createPublicKey(pem);
  if (keyObj.asymmetricKeyType !== "x25519") throw new Error("Website public key must be X25519 (made by npm run keygen)");
  const { keyId } = require("../shared/crypto");
  fs.writeFileSync(
    path.join(root, "exporter", "website-key.generated.js"),
    `"use strict";\n// Generated by scripts/build-exe.js. Do not edit or commit.\nmodule.exports = { WEBSITE_PUBLIC_KEY_PEM: ${JSON.stringify(pem)}, WEBSITE_KEY_ID: ${JSON.stringify(keyId(pem))} };\n`,
  );
  console.log(`  website key id ${keyId(pem)}`);

  step("Bundling with esbuild");
  fs.mkdirSync(dist, { recursive: true });
  const esbuild = require("esbuild");
  await esbuild.build({
    entryPoints: [path.join(root, "exporter", "main.js")],
    bundle: true,
    platform: "node",
    target: `node${major}`,
    format: "cjs",
    outfile: path.join(dist, "exporter.cjs"),
    external: EXTERNALS,
    legalComments: "none",
    logLevel: "warning",
  });

  step("Making the single-executable blob");
  const seaConfig = path.join(dist, "sea-config.json");
  const blob = path.join(dist, "sea-prep.blob");
  fs.writeFileSync(
    seaConfig,
    JSON.stringify({ main: path.join(dist, "exporter.cjs"), output: blob, disableExperimentalSEAWarning: true }, null, 2),
  );
  execFileSync(process.execPath, ["--experimental-sea-config", seaConfig], { stdio: "inherit" });

  step(`Injecting into a copy of ${process.execPath}`);
  const exe = path.join(dist, exeName);
  fs.copyFileSync(process.execPath, exe);
  const { inject } = require("postject");
  await inject(exe, "NODE_SEA_BLOB", fs.readFileSync(blob), {
    sentinelFuse: SENTINEL_FUSE,
    machoSegmentName: process.platform === "darwin" ? "NODE_SEA" : undefined,
  });

  step("Writing SHA256SUMS.txt and README.txt");
  const sum = (f) => crypto.createHash("sha256").update(fs.readFileSync(f)).digest("hex");
  const pkg = require("../package.json");
  fs.writeFileSync(
    path.join(dist, "SHA256SUMS.txt"),
    `${sum(exe)}  ${exeName}\n${sum(path.join(dist, "exporter.cjs"))}  exporter.cjs\n`,
  );
  fs.writeFileSync(
    path.join(dist, "README.txt"),
    [
      `NAVY Payslip Exporter v${pkg.version} (built with Node ${process.version})`,
      `Website key id: ${keyId(pem)}`,
      "",
      "Double-click navy-sync-exporter.exe, or run it in a command window.",
      "  (no option)      Connect -> Export -> Done",
      "  --dry-run        timing test package (never applied by the website)",
      "  --setup          change server, login or database names",
      "  --show-key       print this machine's exporter key for registration on the website",
      "  --ledger         list exported packages",
      "  --discard-last   mark the last package as never uploaded",
      "",
      "Settings, the exporter key and the ledger are kept in %ProgramData%\\navy-payslip-sync.",
      "The program makes no internet connections and opens no ports. It only reads the payroll databases",
      "with the read-only login you type, and writes one .npsync file to the folder you choose.",
      "",
      "Check the file hashes in SHA256SUMS.txt before bringing the program in.",
      "",
    ].join("\r\n"),
  );
  console.log(`\nBuilt ${exe}\n  sha256 ${sum(exe)}`);
  if (isWin) console.log("  Note: injecting removes Node's code signature; Windows may show an 'unknown publisher' prompt.");
}

main().catch((err) => {
  console.error(`\nbuild-exe failed: ${err.message}`);
  console.error("Fallback: run dist/exporter.cjs with a portable node.exe (see the top of this script).");
  process.exitCode = 1;
});
